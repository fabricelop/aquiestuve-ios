    static func options(for family: String, query: String) -> [DetailedCategory] {
        let needle = query.trimmingCharacters(in: .whitespacesAndNewlines)
        let folded = needle.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: .current)
        return all.filter { item in
            guard item.family == family else { return false }
            if folded.isEmpty { return true }
            return (item.name + " " + item.family)
                .folding(options: [.caseInsensitive, .diacriticInsensitive], locale: .current)
                .contains(folded)
        }
    }
}

struct CategoryPickerView: View {
    @Environment(\.dismiss) private var dismiss
    @Binding var selection: String
    @State private var query = ""

    var body: some View {
        NavigationStack {
            List {
                ForEach(CategoryCatalog.families, id: \.self) { family in
                    let items = CategoryCatalog.options(for: family, query: query)
                    if !items.isEmpty {
                        Section(family) {
                            ForEach(items) { item in
                                Button {
                                    selection = item.name
                                    dismiss()
                                } label: {
                                    HStack {
                                        Text(item.name).foregroundStyle(.primary)
                                        Spacer()
                                        if selection == item.name {
                                            Image(systemName: "checkmark.circle.fill")
                                                .foregroundStyle(.indigo)
                                        }
                                    }
                                }
                            }
                        }
                    }
                }
            }
            .searchable(text: $query, prompt: "Buscar entre categorías")
            .navigationTitle("Elegir categoría")
            .navigationBarTitleDisplayMode(.inline)
            .toolbar {
                ToolbarItem(placement: .confirmationAction) {
                    Button("Cerrar") { dismiss() }
                }
            }
        }
    }
}
